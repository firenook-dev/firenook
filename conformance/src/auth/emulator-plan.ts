function lookup(id: string, tokenStep: string): Step {
  return post(id, client(`${V1}/accounts:lookup`), { idToken: `{{token:${tokenStep}}}` });
}

function adminLookup(id: string, localId: string): Step {
  return owner(id, "POST", `${PROJECT}/accounts:lookup`, { localId: [localId] });
}

function configureBlocking(id: string, events: readonly ("beforeCreate" | "beforeSignIn")[], forward?: Json): Step {
  const triggers: { [key: string]: Json } = {};
  for (const event of events) {
    triggers[event] = { functionUri: `{{functionsOrigin}}/blocking/${event}` };
  }
  const blockingFunctions: { [key: string]: Json } = { triggers };
  if (forward) blockingFunctions.forwardInboundCredentials = forward;
  return owner(id, "PATCH", `${PROJECT_V2}/config`, { blockingFunctions }, { query: { updateMask: "blockingFunctions" } });
}

const userRecordUpdate = (fields: { [key: string]: Json }, mask: string): StubResponse => ({
  body: { userRecord: { updateMask: mask, ...fields } },
});

