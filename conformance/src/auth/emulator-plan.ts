export type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

export interface StubResponse {
  readonly status?: number;
  readonly body?: Json | string;
}

export interface Step {
  readonly id: string;
  readonly note?: string;
  readonly method: "GET" | "POST" | "PATCH" | "DELETE" | "PUT" | "OPTIONS";
  readonly path: string;
  readonly query?: Readonly<Record<string, string>>;
  readonly headers?: Readonly<Record<string, string>>;
  readonly body?: Json | string;
  /** Responses the functions stub returns to blocking calls during this step. */
  readonly functions?: { readonly beforeCreate?: StubResponse; readonly beforeSignIn?: StubResponse };
  /** The response body is HTML: record a digest and the extracted account entries. */
  readonly html?: boolean;
  /** The response body is large and static: record its size and digest only. */
  readonly digest?: boolean;
  /** Wait before the request: validSince has one-second resolution, so a token
   *  issued in the same second as a revocation would still be valid. */
  readonly sleepMs?: number;
}

export interface Program {
  readonly id: string;
  readonly category: string;
  readonly title: string;
  readonly steps: readonly Step[];
}

const OWNER = { Authorization: "Bearer owner" } as const;

function client(path: string): string {
  return `${path}?key=${API_KEY}`;
}

function post(id: string, path: string, body: Json, extra: Partial<Step> = {}): Step {
  return { id, method: "POST", path, body, ...extra };
}

function owner(id: string, method: Step["method"], path: string, body?: Json, extra: Partial<Step> = {}): Step {
  return { id, method, path, headers: OWNER, ...(body === undefined ? {} : { body }), ...extra };
}

function get(id: string, path: string, extra: Partial<Step> = {}): Step {
  return { id, method: "GET", path, ...extra };
}

function unsignedJwt(payload: Json): string {
  const header = Buffer.from(JSON.stringify({ alg: "none", typ: "JWT" })).toString("base64url");
  return `${header}.${Buffer.from(JSON.stringify(payload)).toString("base64url")}.`;
}

function signedJwt(payload: Json): string {
  const header = Buffer.from(JSON.stringify({ alg: "HS256", typ: "JWT" })).toString("base64url");
  const body = Buffer.from(JSON.stringify(payload)).toString("base64url");
  const signature = createHmac("sha256", "oracle-fake-secret").update(`${header}.${body}`).digest("base64url");
  return `${header}.${body}.${signature}`;
}

/**
 * A custom token whose claims reference templates is encoded by the capture
 * and the replay after resolution: `{ $customToken: payload }`.
 */
export function deferredCustomToken(uid: string, extra: { [key: string]: Json } = {}): Json {
  return { $customToken: customTokenPayload(uid, extra, CUSTOM_TOKEN_AUDIENCE) };
}

export function customTokenPayload(uid: string, extra: { [key: string]: Json }, aud: string): { [key: string]: Json } {
  return {
    iss: "firebase-adminsdk@fireside-auth-oracle.iam.gserviceaccount.com",
    sub: "firebase-adminsdk@fireside-auth-oracle.iam.gserviceaccount.com",
    aud,
    iat: 1700000000,
    exp: 1700003600,
    uid,
    ...extra,
  };
}

export function encodeUnsignedJwt(payload: Json): string {
  return unsignedJwt(payload);
}

export function customToken(uid: string, extra: { [key: string]: Json } = {}, aud: string = CUSTOM_TOKEN_AUDIENCE): string {
  return unsignedJwt({
    iss: "firebase-adminsdk@fireside-auth-oracle.iam.gserviceaccount.com",
    sub: "firebase-adminsdk@fireside-auth-oracle.iam.gserviceaccount.com",
    aud,
    iat: 1700000000,
    exp: 1700003600,
    uid,
    ...extra,
  });
}

/** A fake IdP credential as the emulator's own widget produces it. */
function idpBody(providerId: string, claims: { [key: string]: Json }, extra: { [key: string]: Json } = {}): Json {
  return {
    requestUri: "http://localhost",
    postBody: `providerId=${providerId}&id_token=${encodeURIComponent(JSON.stringify(claims))}`,
    returnSecureToken: true,
    ...extra,
  };
}

