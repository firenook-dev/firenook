// (firebase-tools 15.22.0). Every program runs on a fresh emulator instance;
// every step is one raw HTTP request. Values produced by earlier steps are
// referenced through templates (`{{token:step}}`, `{{oob:step}}`, ...) that the
// capture resolves from the recording and the replay from its own run.

