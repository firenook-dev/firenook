// The saved cases as a test file for CI: `@firebase/rules-unit-testing`
// with the modular Firebase SDK's Storage functions, one test per case.
// Each uploads the file it read first, as it was when the case was saved
// (its size, type and custom metadata), with the rules out of the way, then
// asserts the verdict with the call an app makes: `getMetadata` for get,
// `listAll` for list, `uploadBytes` with a buffer of the size and the
// metadata for create, `updateMetadata` for update, `deleteObject` for
// delete. Run it with the Storage emulator up —
// `firebase emulators:exec --only storage`.

import { contextCode } from '@/rules/who'
import { folderOf, metadataOf, toBytes } from './requests'
import type { TestCase } from './tests-store'

function quote(text: string): string {
  return JSON.stringify(text)
}

/** `{ contentType, customMetadata }` as SDK metadata, or nothing to pass. */
function metadataCode(
  contentType: string | null | undefined,
  custom: Record<string, string | null>,
): string | undefined {
  const parts: string[] = []
  if (contentType) parts.push(`contentType: ${quote(contentType)}`)
  const entries = Object.entries(custom)
  if (entries.length > 0) {
    const body = `{ ${entries.map(([key, value]) => `${quote(key)}: ${value === null ? 'null' : quote(value)}`).join(', ')} }`
    // `null` removes a key; the SDK's type has strings only.
    parts.push(
      entries.some(([, value]) => value === null)
        ? `customMetadata: ${body} as unknown as Record<string, string>`
        : `customMetadata: ${body}`,
    )
  }
  return parts.length === 0 ? undefined : `{ ${parts.join(', ')} }`
}

/** The setup that uploads the file a case read, as it was, with the rules out of the way. */
function seedCode(test: TestCase, bucket: string): string | undefined {
  const seed = test.seed
  if (!seed || test.form.method === 'list') return undefined
  const metadata = metadataCode(seed.contentType, seed.metadata) ?? '{}'
  return [
    '  await env.withSecurityRulesDisabled(async (context) => {',
    `    const storage = context.storage(${quote(`gs://${bucket}`)})`,
    `    await uploadBytes(ref(storage, ${quote(seed.name)}), new Uint8Array(${seed.size}), ${metadata})`,
    '  })',
  ].join('\n')
}

/** The call a case makes, as the app would. */
export function operationCode(test: TestCase): string {
  const form = test.form
  const path = quote(form.method === 'list' ? folderOf(form.path) : form.path)
  const custom = metadataOf(form.metadata, form.method)
  switch (form.method) {
    case 'get':
      return `getMetadata(ref(storage, ${path}))`
    case 'list':
      return `listAll(ref(storage, ${path}))`
    case 'delete':
      return `deleteObject(ref(storage, ${path}))`
    case 'create': {
      const bytes = toBytes(form.size, form.unit) ?? 0
      const metadata = metadataCode(form.contentType.trim() || null, custom)
      return `uploadBytes(ref(storage, ${path}), new Uint8Array(${bytes})${metadata ? `, ${metadata}` : ''})`
    }
    case 'update':
      return `updateMetadata(ref(storage, ${path}), ${metadataCode(form.contentType.trim() || null, custom) ?? '{}'})`
  }
}

/** The file, for a project id, the bucket the cases default to and the path of its rules file. */
export function exportTests(
  tests: readonly TestCase[],
  options: { project: string; bucket: string; rulesFile: string },
): string {
  const lines = [
    '// Generated by the Firenook console from saved Storage rules tests.',
    `// ${tests.length} test${tests.length === 1 ? '' : 's'} against ${options.rulesFile}.`,
    '// Run with the Storage emulator up, for example:',
    '//   firebase emulators:exec --only storage "npx vitest run"',
    '// Firestore documents the rules read with firestore.get() or firestore.exists()',
    '// are not set up here; add them in beforeEach when a test depends on one.',
    "import { readFileSync } from 'node:fs'",
    "import { afterAll, beforeAll, beforeEach, test } from 'vitest'",
    'import {',
    '  assertFails,',
    '  assertSucceeds,',
    '  initializeTestEnvironment,',
    '  type RulesTestEnvironment,',
    "} from '@firebase/rules-unit-testing'",
    'import {',
    '  deleteObject,',
    '  getMetadata,',
    '  listAll,',
    '  ref,',
    '  updateMetadata,',
    '  uploadBytes,',
    "} from 'firebase/storage'",
    '',
    'let env: RulesTestEnvironment',
    '',
    'beforeAll(async () => {',
    '  env = await initializeTestEnvironment({',
    `    projectId: ${quote(options.project)},`,
    `    storage: { rules: readFileSync(${quote(options.rulesFile)}, 'utf8') },`,
    '  })',
    '})',
    '',
    'afterAll(() => env.cleanup())',
    'beforeEach(() => env.clearStorage())',
  ]
  for (const test of tests) {
    const bucket = test.form.bucket || options.bucket
    const verdict = test.expected === 'allow' ? 'is allowed' : 'is denied'
    lines.push('', `test(${quote(`${test.name} ${verdict}`)}, async () => {`)
    const seed = seedCode(test, bucket)
    if (seed) lines.push(seed)
    lines.push(
      `  const storage = ${contextCode(test.form.who)}.storage(${quote(`gs://${bucket}`)})`,
    )
    lines.push(
      `  await ${test.expected === 'allow' ? 'assertSucceeds' : 'assertFails'}(${operationCode(test)})`,
    )
    lines.push('})')
  }
  return `${lines.join('\n')}\n`
}
