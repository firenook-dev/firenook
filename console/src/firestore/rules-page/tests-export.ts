// The saved cases as a test file for CI: `@firebase/rules-unit-testing`
// with the modular Firebase SDK, one test per case, each setting up the
// document it read as it was when the case was saved, then asserting the
// verdict. Run under Vitest (or Jest, by changing the import) with the
// Firestore emulator up — `firebase emulators:exec --only firestore`.

import { type WorkbenchQuery, parseQuery } from '../query'
import { INFER, type FsValue, decodeFields, fromJson } from '../value'
import type { FirestoreRestValue } from '@/api/generated/FirestoreRestValue'
import { contextCode } from '@/rules/who'
import type { TestCase } from './tests-store'

/** A Firestore value as JavaScript source for the modular SDK. */
export function valueCode(value: FsValue, db: string): string {
  switch (value.type) {
    case 'string':
      return JSON.stringify(value.value)
    case 'number':
      return Number.isFinite(value.value)
        ? String(value.value)
        : `Number(${JSON.stringify(String(value.value))})`
    case 'boolean':
      return String(value.value)
    case 'null':
      return 'null'
    case 'timestamp':
      return `Timestamp.fromDate(new Date(${JSON.stringify(value.value)}))`
    case 'reference':
      return `doc(${db}, ${JSON.stringify(value.path)})`
    case 'geopoint':
      return `new GeoPoint(${value.latitude}, ${value.longitude})`
    case 'bytes':
      return `Bytes.fromBase64String(${JSON.stringify(value.base64)})`
    case 'vector':
      return `vector([${value.values.join(', ')}])`
    case 'array':
      return `[${value.items.map((item) => valueCode(item, db)).join(', ')}]`
    case 'map':
      return fieldsCode(value.fields, db)
  }
}

function fieldsCode(fields: Record<string, FsValue>, db: string): string {
  const entries = Object.entries(fields)
  if (entries.length === 0) return '{}'
  return `{ ${entries.map(([key, item]) => `${keyCode(key)}: ${valueCode(item, db)}`).join(', ')} }`
}

function keyCode(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)
}

function queryCode(query: WorkbenchQuery): string[] {
  const parts: string[] = []
  for (const clause of query.where)
    parts.push(
      `where(${JSON.stringify(clause.field)}, ${JSON.stringify(clause.op)}, ${valueCode(clause.value, 'db')})`,
    )
  for (const order of query.orderBy)
    parts.push(
      `orderBy(${JSON.stringify(order.field)}${order.direction === 'desc' ? ", 'desc'" : ''})`,
    )
  return parts
}

function dataCode(test: TestCase): string {
  try {
    const value = fromJson(test.form.data.trim() ? JSON.parse(test.form.data) : {}, INFER)
    return value.type === 'map' ? fieldsCode(value.fields, 'db') : '{}'
  } catch {
    return '{}'
  }
}

function operationCode(test: TestCase): string {
  const form = test.form
  const path = JSON.stringify(form.path.trim().replace(/^\/+|\/+$/g, ''))
  switch (form.method) {
    case 'get':
      return `getDoc(doc(db, ${path}))`
    case 'delete':
      return `deleteDoc(doc(db, ${path}))`
    case 'create':
      return `setDoc(doc(db, ${path}), ${dataCode(test)})`
    case 'update':
      return `updateDoc(doc(db, ${path}), ${dataCode(test)})`
    case 'list': {
      let query: WorkbenchQuery | undefined
      try {
        query = form.query.trim() ? parseQuery(form.query) : undefined
      } catch {
        query = undefined
      }
      const source = form.group ? `collectionGroup(db, ${path})` : `collection(db, ${path})`
      const parts = query ? queryCode(query) : []
      if (query && form.query.includes('limit(')) parts.push(`limit(${query.limit})`)
      return `getDocs(${parts.length > 0 ? `query(${source}, ${parts.join(', ')})` : source})`
    }
  }
}

function seedCode(test: TestCase): string | undefined {
  if (!test.seed || test.form.method === 'list' || test.form.method === 'create') return undefined
  const fields = decodeFields(test.seed as never)
  const path = JSON.stringify(test.form.path.trim().replace(/^\/+|\/+$/g, ''))
  return [
    '  await env.withSecurityRulesDisabled(async (context) => {',
    '    const db = context.firestore()',
    `    await setDoc(doc(db, ${path}), ${fieldsCode(fields, 'db')})`,
    '  })',
  ].join('\n')
}

/** The file, for a project id and the path of its rules file. */
export function exportTests(
  tests: readonly TestCase[],
  options: { project: string; rulesFile: string },
): string {
  const lines = [
    '// Generated by the Firenook console from saved rules tests.',
    `// ${tests.length} test${tests.length === 1 ? '' : 's'} against ${options.rulesFile}.`,
    '// Run with the Firestore emulator up, for example:',
    '//   firebase emulators:exec --only firestore "npx vitest run"',
    '// Documents the rules read with get() or exists() are not set up here;',
    '// add them in beforeEach when a test depends on one.',
    "import { readFileSync } from 'node:fs'",
    "import { afterAll, beforeAll, beforeEach, test } from 'vitest'",
    'import {',
    '  assertFails,',
    '  assertSucceeds,',
    '  initializeTestEnvironment,',
    '  type RulesTestEnvironment,',
    "} from '@firebase/rules-unit-testing'",
    'import {',
    '  Bytes,',
    '  GeoPoint,',
    '  Timestamp,',
    '  collection,',
    '  collectionGroup,',
    '  deleteDoc,',
    '  doc,',
    '  getDoc,',
    '  getDocs,',
    '  limit,',
    '  orderBy,',
    '  query,',
    '  setDoc,',
    '  updateDoc,',
    '  vector,',
    '  where,',
    "} from 'firebase/firestore'",
    '',
    'let env: RulesTestEnvironment',
    '',
    'beforeAll(async () => {',
    '  env = await initializeTestEnvironment({',
    `    projectId: ${JSON.stringify(options.project)},`,
    `    firestore: { rules: readFileSync(${JSON.stringify(options.rulesFile)}, 'utf8') },`,
    '  })',
    '})',
    '',
    'afterAll(() => env.cleanup())',
    'beforeEach(() => env.clearFirestore())',
  ]
  for (const test of tests) {
    const verdict = test.expected === 'allow' ? 'is allowed' : 'is denied'
    lines.push('', `test(${JSON.stringify(`${test.name} ${verdict}`)}, async () => {`)
    const seed = seedCode(test)
    if (seed) lines.push(seed)
    lines.push(`  const db = ${contextCode(test.form.who)}.firestore()`)
    lines.push(
      `  await ${test.expected === 'allow' ? 'assertSucceeds' : 'assertFails'}(${operationCode(test)})`,
    )
    lines.push('})')
  }
  return `${lines.join('\n')}\n`
}

