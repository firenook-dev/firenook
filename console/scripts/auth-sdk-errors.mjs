// Writes src/auth/sdk-errors.gen.ts: what the Firebase JS SDK calls each
// error the Auth emulator answers with (`INVALID_PASSWORD` →
// `auth/wrong-password`), and the SDK's own sentence for each of its codes,
// read from the pinned @firebase/auth build the conformance harness installs.
//
//   node scripts/auth-sdk-errors.mjs [path/to/@firebase/auth/dist/index.webworker.js]
//
// The default path is the conformance harness's install. The map is read
// from the SDK's own source: `SERVER_ERROR_MAP`, the three codes
// `_performFetchWithErrorHandling` turns into tagged errors before it
// consults the map, and `_debugErrorMap()`'s sentences. Both literals are
// evaluated alone in an empty context; nothing else of the SDK runs. Codes
// the map does not list follow the SDK's fallback rule, applied in
// `src/auth/errors.ts`.

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { runInNewContext } from 'node:vm'

const HERE = dirname(fileURLToPath(import.meta.url))
const source = resolve(
  process.argv[2] ??
    join(HERE, '../../conformance/node_modules/@firebase/auth/dist/index.webworker.js'),
)
const target = join(HERE, '../src/auth/sdk-errors.gen.ts')

const text = readFileSync(source, 'utf8')
const { version } = JSON.parse(readFileSync(join(dirname(source), '../package.json'), 'utf8'))

/** The object literal after `head`, up to the brace that closes it. */
function literalAfter(head) {
  const at = text.indexOf(head)
  if (at === -1) throw new Error(`${head} is not in ${source}`)
  const open = text.indexOf('{', at + head.length - 1)
  let depth = 0
  let quote = ''
  for (let index = open; index < text.length; index += 1) {
    const char = text[index]
    if (quote) {
      if (char === '\\') index += 1
      else if (char === quote) quote = ''
      continue
    }
    if (char === "'" || char === '"' || char === '`') quote = char
    else if (char === '{') depth += 1
    else if (char === '}') {
      depth -= 1
      if (depth === 0) return text.slice(open, index + 1)
    }
  }
  throw new Error(`the literal after ${head} does not close`)
}

/** Evaluates an object literal of strings with nothing in scope. */
function evaluate(literal) {
  return runInNewContext(`(${literal})`, Object.create(null), { timeout: 1000 })
}

const serverMap = evaluate(literalAfter('const SERVER_ERROR_MAP = {'))
const messages = evaluate(literalAfter('function _debugErrorMap() {\n    return {'))

// `if (serverErrorCode === "EMAIL_EXISTS") throw _makeTaggedError(auth, "email-already-in-use", …)`:
// answered before the map is consulted.
const tagged = {}
for (const match of text.matchAll(
  /serverErrorCode === "([A-Z_]+)"[^\n]*\n\s*throw _makeTaggedError\(auth, "([a-z-]+)"/g,
))
  tagged[match[1]] = match[2]
for (const code of ['EMAIL_EXISTS', 'USER_DISABLED', 'FEDERATED_USER_ID_ALREADY_LINKED'])
  if (!tagged[code])
    throw new Error(`${code} is no longer answered before the map; read the SDK again`)

const map = { ...serverMap, ...tagged }
const sorted = (record) =>
  Object.fromEntries(Object.entries(record).toSorted(([a], [b]) => (a < b ? -1 : 1)))

const lines = [
  '// Generated by console/scripts/auth-sdk-errors.mjs from @firebase/auth',
  `// ${version} (SERVER_ERROR_MAP, the tagged errors of`,
  '// _performFetchWithErrorHandling, and _debugErrorMap). Do not edit; run the',
  '// script again against a newer SDK instead.',
  '',
  '/** The @firebase/auth version this was read from. */',
  `export const SDK_VERSION = '${version}'`,
  '',
  '/** What the JS SDK calls an emulator error code, without the `auth/` prefix. */',
  `export const SERVER_ERROR_MAP: Readonly<Record<string, string>> = ${JSON.stringify(sorted(map), null, 2)}`,
  '',
  '/** The SDK’s own sentence for each of its codes, as `error.message` carries it. */',
  `export const SDK_MESSAGES: Readonly<Record<string, string>> = ${JSON.stringify(sorted(messages), null, 2)}`,
  '',
]
writeFileSync(target, lines.join('\n'))
// In the console's own style, so a run leaves nothing for the formatter to change.
execFileSync(join(HERE, '../node_modules/.bin/oxfmt'), [target], { stdio: 'ignore' })
console.log(
  `wrote ${target}: ${Object.keys(map).length} server codes, ${Object.keys(messages).length} SDK messages (@firebase/auth ${version})`,
)
